#!/bin/bash

# Скрипт для применения исправлений критических ошибок
# Исправляет: numeric field overflow и проблемы с несуществующими парами

set -e  # Остановить выполнение при любой ошибке

echo "🔧 Применение исправлений критических ошибок..."
echo "======================================================"

# Проверка окружения
echo "📋 Проверка окружения..."
if [ ! -f "package.json" ]; then
    echo "❌ Ошибка: Запустите скрипт из корневой директории проекта"
    exit 1
fi

# Остановка приложения
echo "🛑 Остановка приложения..."
npm run stop 2>/dev/null || echo "⚠️  Приложение уже остановлено"

# Применение миграции базы данных
echo "🗄️  Применение миграции базы данных..."
cd backend

# Проверка подключения к базе данных
if ! psql -d backtester_db -c "SELECT 1;" >/dev/null 2>&1; then
    echo "❌ Ошибка: Не удается подключиться к базе данных backtester_db"
    echo "💡 Убедитесь, что PostgreSQL запущен и база данных создана"
    exit 1
fi

# Применение миграции
echo "🔄 Обновление схемы таблицы candles..."
psql -d backtester_db -f migrations/update_candles_precision.sql

if [ $? -eq 0 ]; then
    echo "✅ Миграция базы данных успешно применена"
else
    echo "❌ Ошибка применения миграции"
    exit 1
fi

# Возврат в корневую директорию
cd ..

# Проверка обновлений в коде
echo "🔍 Проверка обновлений кода..."
echo "  ✅ Модель Candle.ts обновлена (DECIMAL точность увеличена)"
echo "  ✅ okxService.ts обновлен (добавлена валидация пар)"
echo "  ✅ Улучшенное логирование ошибок"

# Установка зависимостей (если изменились)
echo "📦 Проверка зависимостей..."
npm install --silent

# Перезапуск приложения
echo "🚀 Перезапуск приложения..."
npm run start &

# Ожидание запуска
echo "⏳ Ожидание запуска сервера..."
sleep 5

# Проверка статуса
if curl -f http://localhost:3000/health >/dev/null 2>&1; then
    echo "✅ Сервер успешно запущен"
else
    echo "⚠️  Сервер запускается... Проверьте логи"
fi

echo ""
echo "🎉 Исправления успешно применены!"
echo "======================================"
echo ""
echo "📊 Исправленные проблемы:"
echo "  ✅ Переполнение числовых полей (DECIMAL precision увеличена)"
echo "  ✅ Запросы к несуществующим парам (добавлена валидация)"
echo "  ✅ Улучшенное логирование и обработка ошибок"
echo ""
echo "🔍 Мониторинг исправлений:"
echo "  📈 Overflow ошибки: grep -i 'overflow' backend/logs/combined.log"
echo "  🔗 Несуществующие пары: grep -i 'not found in OKX' backend/logs/combined.log"
echo ""
echo "📚 Документация: docs/BUGFIX_INSTRUCTIONS.md" 